def _read(path, default=None):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return default


def _write(path, obj):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
    os.replace(tmp, path)


def get_settings():
    with _lock:
        s = copy.deepcopy(DEFAULT_SETTINGS)
        saved = _read(os.path.join(DATA, "settings.json"), {}) or {}
        s.update({k: v for k, v in saved.items() if k != "styles"})
        for k, v in (saved.get("styles") or {}).items():
            s["styles"][k] = {**s["styles"].get(k, DEFAULT_STYLES["documentary"]), **v}
        # environment variables win, handy for hosting
        for env, key in (("ANTHROPIC_API_KEY", "anthropic_key"), ("PEXELS_API_KEY", "pexels_key"),
                         ("PIXABAY_API_KEY", "pixabay_key"), ("OPENAI_API_KEY", "openai_key")):
            if os.environ.get(env) and not s.get(key):
                s[key] = os.environ[env]
        return s


def save_settings(patch):
    with _lock:
        path = os.path.join(DATA, "settings.json")
        saved = _read(path, {}) or {}
        saved.update(patch)
        _write(path, saved)
    return get_settings()


