def upsert_profile(data):
    lst = get_profiles()
    if not data.get("id"):
        data["id"] = uuid.uuid4().hex[:8]
        data["created"] = time.time()
        lst.append(data)
    else:
        lst = [dict(x, **data) if x.get("id") == data["id"] else x for x in lst]
    save_profiles(lst)
    return get_profile(data["id"])
