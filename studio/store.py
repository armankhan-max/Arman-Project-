def _read(path, default=None):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return default


def _write(path, obj):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
    os.replace(tmp, path)


def get_settings():
    with _lock:
        s = copy.deepcopy(DEFAULT_SETTINGS)
        saved = _read(os.path.join(DATA, "settings.json"), {}) or {}
        s.update({k: v for k, v in saved.items() if k != "styles"})
        for k, v in (saved.get("styles") or {}).items():
            s["styles"][k] = {**s["styles"].get(k, DEFAULT_STYLES["documentary"]), **v}
        # environment variables win, handy for hosting
        for env, key in (("ANTHROPIC_API_KEY", "anthropic_key"), ("PEXELS_API_KEY", "pexels_key"),
                         ("PIXABAY_API_KEY", "pixabay_key"), ("OPENAI_API_KEY", "openai_key")):
            if os.environ.get(env) and not s.get(key):
                s[key] = os.environ[env]
        return s


def save_settings(patch):
    with _lock:
        path = os.path.join(DATA, "settings.json")
        saved = _read(path, {}) or {}
        saved.update(patch)
        _write(path, saved)
    return get_settings()


def get_auth():
    return _read(os.path.join(DATA, "auth.json"), {}) or {}


def save_auth(a):
    with _lock:
        _write(os.path.join(DATA, "auth.json"), a)


def pdir(pid):
    return os.path.join(PROJECTS, pid)


def new_project(data):
    pid = time.strftime("%y%m%d") + "-" + uuid.uuid4().hex[:6]
    os.makedirs(pdir(pid), exist_ok=True)
    data = {"id": pid, "created": time.time(), "status": "new", "progress": 0, "step": "", "log": [],
            "scenes": [], **data}
    save_project(data)
    return data


def get_project(pid):
    if not pid or "/" in pid or ".." in pid:
        return None
    return _read(os.path.join(pdir(pid), "project.json"))


def save_project(p):
    with _lock:
        _write(os.path.join(pdir(p["id"]), "project.json"), p)


def update_project(pid, **patch):
    with _lock:
        p = get_project(pid)
        if p:
            p.update(patch)
            save_project(p)
        return p


def list_projects():
    out = []
    for pid in os.listdir(PROJECTS):
        p = get_project(pid)
        if p:
            out.append({k: p.get(k) for k in ("id", "title", "style", "status", "progress", "step", "created",
                                               "duration", "video", "thumb", "aspect")})
    return sorted(out, key=lambda x: -(x.get("created") or 0))
