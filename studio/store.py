def pdir(pid):
    return os.path.join(PROJECTS, pid)


def new_project(data):
    pid = time.strftime("%y%m%d") + "-" + uuid.uuid4().hex[:6]
    os.makedirs(pdir(pid), exist_ok=True)
    data = {"id": pid, "created": time.time(), "status": "new", "progress": 0, "step": "", "log": [],
            "scenes": [], **data}
    save_project(data)
    return data


def get_project(pid):
    if not pid or "/" in pid or ".." in pid:
        return None
    return _read(os.path.join(pdir(pid), "project.json"))


def save_project(p):
    with _lock:
        _write(os.path.join(pdir(p["id"]), "project.json"), p)


def update_project(pid, **patch):
    with _lock:
        p = get_project(pid)
        if p:
            p.update(patch)
            save_project(p)
        return p


def list_projects():
    out = []
    for pid in os.listdir(PROJECTS):
        p = get_project(pid)
        if p:
            out.append({k: p.get(k) for k in ("id", "title", "style", "status", "progress", "step", "created",
                                               "duration", "video", "thumb", "aspect")})
    return sorted(out, key=lambda x: -(x.get("created") or 0))


